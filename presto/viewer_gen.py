#!/usr/bin/env python3
"""presto/viewer_nets.h from web/panel.json: the networks as the web demo draws them, sparse, for the on-screen viewer.
  python3 presto/viewer_gen.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, "..", "web", "panel.json")))
o = ["// Generated by presto/viewer_gen.py from web/panel.json. Do not edit.", "#pragma once", "#include <stdint.h>",
     "typedef struct { uint8_t lvl, u, u2, u3; float scale; } vcell_t;      // (u2 != 255: an aim let through: u2 - u + u3, scale 1)",
     "typedef struct { uint8_t c, a, b; } vlink_t;",
     "typedef struct { int nl; const uint16_t *size, *row, *idx; const float *w, *b; int ncol; const uint8_t *colsize; const vcell_t *cell; int nlink; const vlink_t *link; const uint8_t *out; const float *outscale; } vnet_t;"]
OUTS = {"fight": ([0, 1, 3, 2], [31, 8, 40, 1]), "interceptor": ([0, 1, 3, 2], [31, 8, 40, 1]), "camera": ([0, 1, 3, 2], [31, 8, 40, 1]), "dock": ([0, 1, 2, 3], [32, 8, 40, 1])}
def F(x): return "%.7gf" % x if "." in "%.7g" % x or "e" in "%.7g" % x else "%.7g.0f" % x
for name in ("fight", "interceptor", "camera", "dock"):
    N = D[name]; P = "V_" + name.upper(); L = N["layers"]
    size = [len(L[0]["W"][0])] + [len(l["b"]) for l in L]
    row, idx, w, b = [0], [], [], []
    for l in L:
        for r, bias in zip(l["W"], l["b"]):
            b.append(bias)
            for j, v in enumerate(r):
                if v: idx.append(j), w.append(v)
            row.append(len(idx))
    if name == "dock":
        cols = N["cols"][:-1]; colsize = [len(c[2]) for c in cols]; cell = []
        for t, li, rows in cols:
            for c in rows:
                if len(c) > 2: cell.append((li, c[0], c[2], c[3], 1.0))
                else: cell.append((li, c[0], 255, 255, N["scale"][li][c[0]] or 1))
        link = [(c, a, b2) for c, a, b2 in N["links"] if c + 1 < len(cols)]
    else:
        colsize = size[:-1]; cell = [(c, r, 255, 255, N["scale"][c][r] or 1) for c in range(len(colsize)) for r in range(colsize[c])]
        link = [(i, j, k) for i, l in enumerate(L[:-1]) for k, r in enumerate(l["W"]) for j, v in enumerate(r) if v]
    arr = lambda t, n, v: f"static const {t} {P}_{n}[] = {{{','.join(v)}}};"
    if name == "fight": o.append("#if !NO_FAIR")
    o += [arr("uint16_t", "SIZE", map(str, size)), arr("uint16_t", "ROW", map(str, row)), arr("uint16_t", "IDX", map(str, idx)), arr("float", "W", map(F, w)), arr("float", "B", map(F, b)),
          arr("uint8_t", "COLSIZE", map(str, colsize)), arr("vcell_t", "CELL", ["{%d,%d,%d,%d,%s}" % (a, c, d, e, F(s)) for a, c, d, e, s in cell]),
          arr("vlink_t", "LINK", ["{%d,%d,%d}" % x for x in link]), arr("uint8_t", "OUT", map(str, OUTS[name][0])), arr("float", "OUTSCALE", map(F, OUTS[name][1])),
          f"static const vnet_t {P} = {{{len(L)},{P}_SIZE,{P}_ROW,{P}_IDX,{P}_W,{P}_B,{len(colsize)},{P}_COLSIZE,{P}_CELL,{len(link)},{P}_LINK,{P}_OUT,{P}_OUTSCALE}};"]
    if name == "fight": o.append("#endif")
open(os.path.join(HERE, "viewer_nets.h"), "w").write("\n".join(o) + "\n")
