"""Write a network three ways: .npz (with every unit's name and note), .wsp (the run-time text the C loads
with WSPW=file), and cplayer/pilot_weights.h (compiled in)."""
import os
import numpy as np
from .features import NAMES as FEATURES

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WSP = os.path.join(ROOT, "wsp")


def arrays(layers):
    return [L.W() for L in layers]


def save_npz(layers, path, params=None):
    d = {}
    for i, L in enumerate(layers):
        W, b = L.W()
        d[f"W{i}"], d[f"b{i}"] = W, b
        d[f"names{i}"], d[f"notes{i}"] = np.array(L.names), np.array(L.notes)
    if params:
        d["param_names"] = np.array(list(params)); d["param_values"] = np.array(list(params.values()), dtype=np.float64)
    np.savez(path, **d, features=np.array(FEATURES))


def save_wsp(Wb, path):
    with open(path, "w") as f:
        f.write(f"WSP2 {len(Wb)}\n")
        for W, b in Wb:
            f.write(f"{W.shape[0]} {W.shape[1]}\n")
            f.write(" ".join(f"{float(v):.9g}" for v in W.ravel()) + "\n")
            f.write(" ".join(f"{float(v):.9g}" for v in b) + "\n")


def save_header(Wb, path, names=None):
    lines = ["// Generated by wsp/elite_wsp/export.py. The run-time WSPW=file overrides it.", "#pragma once",
             f"#define WSP_LAYERS {len(Wb)}",
             "static const int WSP_SHAPE[WSP_LAYERS + 1] = {" + ", ".join([str(Wb[0][0].shape[1])] + [str(W.shape[0]) for W, _ in Wb]) + "};"]
    for i, (W, b) in enumerate(Wb):
        if names:
            lines.append(f"// layer {i}: " + ", ".join(names[i]))
        lines.append(f"static const float WSP_W{i}[{W.size}] = {{" + ", ".join(f"{float(v)!r}f" for v in W.ravel()) + "};")
        lines.append(f"static const float WSP_B{i}[{b.size}] = {{" + ", ".join(f"{float(v)!r}f" for v in b) + "};")
    lines.append("static const float *WSP_W[WSP_LAYERS] = {" + ", ".join(f"WSP_W{i}" for i in range(len(Wb))) + "};")
    lines.append("static const float *WSP_B[WSP_LAYERS] = {" + ", ".join(f"WSP_B{i}" for i in range(len(Wb))) + "};")
    open(path, "w").write("\n".join(lines) + "\n")


def save_all(layers, params=None, stem="elite_pilot"):
    save_npz(layers, os.path.join(WSP, stem + ".npz"), params)
    Wb = arrays(layers)
    save_wsp(Wb, os.path.join(WSP, stem + ".wsp"))
    save_header(Wb, os.path.join(ROOT, "cplayer", "pilot_weights.h"), [L.names for L in layers])
    shape = " -> ".join([str(Wb[0][0].shape[1])] + [str(W.shape[0]) for W, _ in Wb])
    n = sum(W.size + b.size for W, b in Wb)
    return f"wrote {stem}.npz/.wsp and cplayer/pilot_weights.h: {shape}, {n} weights"
