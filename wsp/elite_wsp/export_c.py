"""Emit the authored weights as a C header for the RP2350 build (plain float32 MLP, no library)."""
import sys
from .net import Net


def main(path="elite_pilot.npz", out="c/pilot_weights.h"):
    net = Net(path)
    lines = ["// Generated by elite_wsp.export_c from elite_pilot.npz: weights written by hand, not trained.",
             "#pragma once", f"#define WSP_LAYERS {net.n}", f"#define WSP_IN {net.W[0].shape[1]}",
             f"#define WSP_MAXW {max(W.shape[0] for W in net.W)}",
             "static const int WSP_SHAPE[WSP_LAYERS + 1] = {" + ", ".join(str(net.W[0].shape[1:][0]) if i == 0 else str(net.W[i - 1].shape[0]) for i in range(net.n + 1)) + "};"]
    for i, (W, b) in enumerate(zip(net.W, net.b)):
        lines.append(f"// layer {i}: " + ", ".join(net.names[i]))
        lines.append(f"static const float WSP_W{i}[{W.shape[0]}][{W.shape[1]}] = {{")
        for row in W:
            lines.append("  {" + ", ".join(f"{float(v)!r}f" for v in row) + "},")
        lines.append("};")
        lines.append(f"static const float WSP_B{i}[{b.shape[0]}] = {{" + ", ".join(f"{float(v)!r}f" for v in b) + "};")
    lines.append("static const float *WSP_W[WSP_LAYERS] = {" + ", ".join(f"&WSP_W{i}[0][0]" for i in range(net.n)) + "};")
    lines.append("static const float *WSP_B[WSP_LAYERS] = {" + ", ".join(f"WSP_B{i}" for i in range(net.n)) + "};")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(*sys.argv[1:])
